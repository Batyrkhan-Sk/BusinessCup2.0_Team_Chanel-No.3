/** Renders an AppealPack to a PDF with pdf-lib (runs in the browser; no server needed). */
import { PDFDocument, StandardFonts, rgb, degrees, type PDFFont, type PDFPage } from "pdf-lib";
import type { AppealPack } from "./pack";

const PAGE: [number, number] = [612, 792];
const M = 64;
const INK = rgb(0.086, 0.125, 0.122);
const MUTED = rgb(0.42, 0.46, 0.45);

// pdf-lib's standard fonts only encode WinAnsi; normalise typographic characters.
const clean = (s: string) =>
  s.replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[–—−]/g, "-").replace(/·/g, "-").replace(/→/g, "->").replace(/…/g, "...").replace(/[^\x20-\x7E\xA0-\xFF\n]/g, "");

class Writer {
  page!: PDFPage;
  y = 0;
  constructor(private doc: PDFDocument, private font: PDFFont, private bold: PDFFont, private demo: boolean, private footer: string) {
    this.newPage();
  }
  newPage() {
    this.page = this.doc.addPage(PAGE);
    this.y = PAGE[1] - M;
    if (this.demo) this.page.drawText("DEMO - FICTIONAL", { x: 140, y: 300, size: 60, font: this.bold, color: rgb(0.88, 0.88, 0.88), rotate: degrees(35), opacity: 0.5 });
    this.page.drawText(clean(this.footer), { x: M, y: 36, size: 8, font: this.font, color: MUTED });
  }
  ensure(h: number) {
    if (this.y - h < M) this.newPage();
  }
  text(s: string, opts: { size?: number; bold?: boolean; color?: typeof INK; gap?: number } = {}) {
    const size = opts.size ?? 10.5;
    const font = opts.bold ? this.bold : this.font;
    const width = PAGE[0] - 2 * M;
    for (const para of clean(s).split("\n")) {
      const words = para.split(" ");
      let line = "";
      for (const w of words) {
        const trial = line ? `${line} ${w}` : w;
        if (font.widthOfTextAtSize(trial, size) > width && line) {
          this.ensure(size + 4);
          this.page.drawText(line, { x: M, y: this.y, size, font, color: opts.color ?? INK });
          this.y -= size + 4;
          line = w;
        } else line = trial;
      }
      this.ensure(size + 4);
      this.page.drawText(line, { x: M, y: this.y, size, font, color: opts.color ?? INK });
      this.y -= size + 4;
    }
    this.y -= opts.gap ?? 6;
  }
}

export async function appealPackPdf(pack: AppealPack): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(clean(pack.title));
  doc.setCreator("DoseCost");
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const w = new Writer(doc, font, bold, pack.demo, "Generated by DoseCost from your decoded letter and plan policy data. Not medical, legal or financial advice.");

  // 1. Patient appeal letter
  for (const l of pack.letter.header) w.text(l, { gap: 0 });
  w.y -= 12;
  for (const l of pack.letter.to) w.text(l, { bold: l === pack.letter.to[0], gap: 0 });
  w.y -= 12;
  w.text(pack.letter.re, { bold: true, gap: 10 });
  for (const p of pack.letter.paragraphs) w.text(p, { gap: 10 });
  w.text(`Enclosures: ${pack.letter.enclosures.join("; ")}.`, { gap: 14 });
  for (const l of pack.letter.signoff) w.text(l, { gap: 0 });

  // 2. Letter of medical necessity (draft)
  w.newPage();
  w.text(pack.lmn.title, { bold: true, size: 14, gap: 4 });
  w.text(pack.lmn.note, { color: MUTED, size: 9, gap: 14 });
  for (const s of pack.lmn.sections) {
    w.text(s.heading, { bold: true, gap: 2 });
    w.text(s.body, { gap: 10 });
  }

  // 3. Checklist
  w.newPage();
  w.text("Document checklist", { bold: true, size: 14, gap: 12 });
  for (const c of pack.checklist) {
    w.text(`[  ]  ${c.label}`, { bold: true, gap: 0 });
    w.text(`${c.detail} (${c.who === "doctor" ? "your doctor" : c.who === "dosecost" ? "DoseCost" : "you"})`, { color: MUTED, size: 9.5, gap: 8 });
  }

  // 4. Case summary
  w.y -= 12;
  w.text("Case summary", { bold: true, size: 14, gap: 10 });
  for (const [k, v] of pack.summary) w.text(`${k}: ${v}`, { gap: 2 });

  return doc.save();
}
